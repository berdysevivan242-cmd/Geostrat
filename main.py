class Полоса(Widget):
    def __init__(self, hexc, **kw):
        super().__init__(**kw)
        self._hex = hexc
        self.bind(pos=self._р, size=self._р)
        self._р()

    def _р(self, *a):
        self.canvas.clear()
        with self.canvas:
            Color(self._hex)
            Rectangle(pos=self.pos, size=self.size)


class Карта(Widget):
    def __init__(self, игра, **kw):
        super().__init__(**kw)
        self.игра = игра
        self.поз = {}
        self.bind(pos=self.перерис, size=self.перерис)

    def точка(self, дол, шир):
        x = self.x + dp(6) + (дол + 180) / 360 * (self.width - dp(12))
        y = self.y + (шир + 90) / 180 * self.height
        return x, y

    def перерис(self, *a):
        self.canvas.clear()
        г = self.игра.г
        if not г:
            return
        with self.canvas:
            Color(*ОКЕАН)
            Rectangle(pos=self.pos, size=self.size)
            Color(*СЕТКА)
            for дол in range(-150, 151, 30):
                x, _ = self.точка(дол, 0)
                Line(points=[x, self.y, x, self.top], width=dp(0.5))
            for шир in range(-60, 90, 30):
                _, y = self.точка(0, шир)
                Line(points=[self.x, y, self.right, y], width=dp(0.5))
            for поли in КОНТИНЕНТЫ:
                pts = []
                for дол, шир in поли:
                    x, y = self.точка(дол, шир)
                    pts += [x, y]
                Color(*СУША)
                Polygon(points=pts)
                Color(*СУША2)
                Line(points=pts + pts[:2], width=dp(1))
        self.поз = {}
        with self.canvas:
            for страна, д in СТРАНЫ.items():
                x, y = self.точка(*д[5])
                self.поз[страна] = (x, y)
                cw, ch = dp(14), dp(10)
                цвета = д[6]
                for i, hexc in enumerate(цвета):
                    yy = y + ch / 2 - (i + 1) * ch / len(цвета)
                    Color(hexc)
                    Rectangle(pos=(x - cw / 2, yy),
                              size=(cw, ch / len(цвета) + 0.4))
            if г.get("война") and г["война"] in self.поз:
                x, y = self.поз[г["война"]]
                Color(*КРАСН)
                Line(circle=(x, y, dp(11)), width=dp(2))
            if "Россия" in self.поз:
                x, y = self.поз["Россия"]
                Color(*ЗОЛОТО)
                Line(circle=(x, y, dp(11)), width=dp(2))

    def on_touch_down(self, т):
        if self.collide_point(т.x, т.y):
            лучшая, лучш = None, dp(20) ** 2
            for страна, (x, y) in self.поз.items():
                d = (т.x - x) ** 2 + (т.y - y) ** 2
                if d < лучш:
                    лучшая, лучш = страна, d
            if лучшая and лучшая != "Россия":
                self.игра.открыть_страну(лучшая)
                return True
        return super().on_touch_down(т)

