    def выбор_диалога(self, i):
        в = self._д["варианты"][i]
        self.применить_эфф(в.get("эфф"))
        for c, dv in (в.get("отн") or {}).items():
            self.измен_отн(c, dv)
        сохранить_игру(self, self.г)
        if в.get("ответ"):
            self._д = {"кто": self._д["кто"], "текст": в["ответ"],
                       "варианты": []}
            self.экран_диалог()
        else:
            self.диалог_дальше()

    def диалог_дальше(self, *a):
        п = self._после
        self._после = None
        self._д = None
        if п:
            п()

