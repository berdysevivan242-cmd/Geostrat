    def двигаться(self, *a):
        г = self.г
        if self.проверка_финала():
            return
        if self.этап == "сцены":
            сцен = СЦЕНЫ.get(г["месяц"], [])
            i = г["сц_инд"]
            if i < len(сцен):
                г["сц_инд"] += 1
                сохранить_игру(self, г)
                сц = сцен[i]
                self.диалог(сц["кто"], сц["текст"], сц["варианты"],
                            self.двигаться)
                return
            self.этап = "война"
            self.двигаться()
            return
        if self.этап == "война":
            if г["война"]:
                self.раунд_войны()
                return
            self.этап = "событие"
            self.двигаться()
            return
        if self.этап == "событие":
            if г["стаб"] < 20 and random.random() < 0.1:
                if random.random() < 0.3:
                    г["флаги"].append("убит")
                    сохранить_игру(self, г)
                    self.финал()
                    return
                self.диалог("РАССКАЗЧИК",
                            "Хлопок выстрела у трибуны... Покушение! Вы "
                            "уцелели. Страна в шоке, но судьба вас хранит.",
                            [], self.событие_шаг)
                return
            self.событие_шаг()
            return
        if self.этап == "ии":
            другие = [c for c in СТРАНЫ if c != "Россия"]
            c = random.choice(другие)
            р = self.отн(c)
            if (р < -60 and not г["война"]
                    and random.random() < СТРАНЫ[c][4] / 40):
                г["война"] = c
                сохранить_игру(self, г)
                self.этап = "экономика"
                self.диалог(c, "{} ОБЪЯВЛЯЕТ ВАМ ВОЙНУ! Бронетехника у "
                               "границ.".format(СТРАНЫ[c][0]), [],
                            self.двигаться)
                return
            if р < -25 and random.random() < 0.25:
                г["эк"] -= 2
                self.измен_отн(c, -5)
                сохранить_игру(self, г)
                self.этап = "экономика"
                self.диалог("НОВОСТИ", "{} вводит против России новые "
                            "ограничения: экономика -2.".format(c), [],
                            self.двигаться)
                return
            if р > 55 and random.random() < 0.2:
                г["эк"] += 1
                сохранить_игру(self, г)
                self.этап = "экономика"
                self.диалог("НОВОСТИ", "{} расширяет торговлю с Россией: "
                            "экономика +1.".format(c), [], self.двигаться)
                return
            self.этап = "экономика"
            self.двигаться()
            return
        if self.этап == "экономика":
            г["казна"] += г["эк"] // 12 - 3
            текст = None
            if г["казна"] < 0:
                г["стаб"] -= 3
                текст = ("Казна пуста! Бюджетный кризис бьёт по "
                         "стабильности (-3).")
            сохранить_игру(self, г)
            self.этап = "готово"
            if текст:
                self.диалог("МИНФИН", текст, [], self.двигаться)
                return
            self.двигаться()
            return
        if self.этап == "готово":
            сохранить_игру(self, г)
            self.экран_карта()
            return

    def событие_шаг(self, *a):
        г = self.г
        if random.random() <= 0.45:
            ев = random.choice(СОБЫТИЯ)
            кто = random.choice(["СОВЕТНИК", "ПРАВИТЕЛЬСТВО", "ПРЕССА",
                                 "МИД", "ШТАБ"])
            self.этап = "ии"
            self.диалог(кто, ев["текст"], ев["варианты"], self.двигаться)
            return
        self.этап = "ии"
        self.двигаться()

    def раунд_войны(self):
        г = self.г
        враг = г["война"]
        г["казна"] -= 4
        г["одобр"] -= 2
        союз = 0
        for c in СТРАНЫ:
            if c not in ("Россия", враг) and self.отн(c) > 55:
                if random.random() < 0.5:
                    союз += г["армии"].get(c, СТРАНЫ[c][2]) * 0.15
        моя = г["во"] + союз + random.uniform(-8, 8)
        их = (г["армии"].get(враг, СТРАНЫ[враг][2])
              + г["эк_др"].get(враг, СТРАНЫ[враг][1]) * 0.15
              + random.uniform(-8, 8))
        if моя > их:
            г["армии"][враг] = г["армии"].get(враг, СТРАНЫ[враг][2]) - 8
            г["одобр"] += 2
            сообщ = "Бои успешны: армия противника несёт потери."
        else:
            г["во"] -= 7
            г["эк"] -= 2
            сообщ = "Противник теснит на направлениях. Тяжёлые потери."
        if г["армии"][враг] <= 12:
            сообщ += " ПОБЕДА! {} идёт на переговоры о капитуляции.".format(враг)
            г["эк"] += 8
            г["одобр"] += 8
            for c in СТРАНЫ:
                if c not in ("Россия", враг):
                    self.измен_отн(c, -15)
            г["война"] = None
            г["победа_в_войне"] = True
        elif г["во"] <= 10:
            сообщ += " ПОРАЖЕНИЕ. {} диктует условия.".format(враг)
            г["эк"] -= 12
            г["одобр"] -= 20
            г["стаб"] -= 15
            г["война"] = None
            г["поражение_в_войне"] = True
        сохранить_игру(self, г)
        self.этап = "событие"
        self.диалог("ШТАБ", сообщ, [], self.двигаться)

    def проверка_финала(self):
        г = self.г
        if (г["месяц"] >= 24 or г["стаб"] <= 0 or г["одобр"] <= 0
                or "убит" in г.get("флаги", [])):
            self.финал()
            return True
        return False

    def финал(self):
        г = self.г
        if "убит" in г.get("флаги", []):
            ид = "кон_10"
        elif г["месяц"] >= 24:
            if г["одобр"] >= 60 and г.get("победа_в_войне"):
                ид = "кон_8"
            elif г["одобр"] >= 60:
                ид = "кон_1"
            elif г["одобр"] >= 45:
                ид = "кон_2"
            elif г["одобр"] >= 25:
                ид = "кон_3"
            else:
                ид = "кон_4"
        elif г.get("поражение_в_войне") and г["одобр"] < 25:
            ид = "кон_9"
        elif г["стаб"] <= 0:
            ид = "кон_7" if г["одобр"] >= 40 else "кон_5"
        else:
            ид = "кон_6"
        назв = КОНЦ_СЛОВАРЬ[ид]
        текст = КОНЦ_ТЕКСТ[ид]
        ново = записать_концовку(self, ид, назв)
        стереть_сохранение(self)
        if ново:
            текст = "НОВАЯ КОНЦОВКА!\n\n" + текст
        self.конец = (назв, текст)
        self.г = None
        self.экран_конец()

