def путь(app, имя):
    return os.path.join(app.user_data_dir, имя)

def сохранить_игру(app, г):
    д = dict(г)
    if isinstance(д.get("флаги"), set):
        д["флаги"] = sorted(д["флаги"])
    try:
        with open(путь(app, "save.json"), "w", encoding="utf-8") as f:
            json.dump(д, f, ensure_ascii=False)
    except OSError:
        pass

def загрузить_игру(app):
    try:
        with open(путь(app, "save.json"), "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return None

def стереть_сохранение(app):
    try:
        os.remove(путь(app, "save.json"))
    except OSError:
        pass

def архив_концовок(app):
    try:
        with open(путь(app, "endings.json"), "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return {}

def записать_концовку(app, ид, назв):
    арх = архив_концовок(app)
    ново = ид not in арх
    арх[ид] = назв
    try:
        with open(путь(app, "endings.json"), "w", encoding="utf-8") as f:
            json.dump(арх, f, ensure_ascii=False)
    except OSError:
        pass
    return ново

